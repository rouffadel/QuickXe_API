-- 2. FORCE SYNC to Country table for ALL existing records
UPDATE c
SET c.[CurrencySymbol] = cm.[CurrencySymbol]
FROM [dbo].[Country] c
INNER JOIN [dbo].[CountriesMaster] cm ON LTRIM(RTRIM(c.[CountryCode])) = LTRIM(RTRIM(cm.[CountryCode]))
WHERE cm.[CurrencySymbol] IS NOT NULL;
GO

-- 3. FIX any remaining NULLs in Country table if match was found
UPDATE [dbo].[Country]
SET [CurrencySymbol] = cm.[CurrencySymbol]
FROM [dbo].[Country] c
JOIN [dbo].[CountriesMaster] cm ON LTRIM(RTRIM(c.[CountryCode])) = LTRIM(RTRIM(cm.[CountryCode]))
WHERE c.[CurrencySymbol] IS NULL;
